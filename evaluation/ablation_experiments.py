"""Ablation experiment harness comparing ByteTrack variants on synthetic & real benchmarks.

NOTE: Synthetic occlusion sequences generated by ``generate_occlusion_benchmark`` are
labeled ``data_kind="synthetic"`` and serve strictly for module diagnostics and unit tests.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from pathlib import Path
import time
from typing import Dict, List, Optional, Tuple
import numpy as np
from scipy.optimize import linear_sum_assignment

from core.byte_tracker import ByteTracker, ByteTrackerConfig
from core.detector_adapter import Detection, DetectorAdapter
from core.matching import bbox_iou_matrix


# VisDrone2019-MOT categories -> COCO class IDs (0=person, 1=bicycle, 2=car, 3=motorcycle, 5=bus, 7=truck).
# Category 0 (ignored regions) and 11 (others) are intentionally excluded.
VISDRONE_TO_COCO_MAP: Dict[int, int] = {
    1: 0,   # pedestrian -> person
    2: 0,   # people -> person
    3: 1,   # bicycle -> bicycle
    4: 2,   # car -> car
    5: 2,   # van -> car
    6: 7,   # truck -> truck
    7: 3,   # tricycle -> motorcycle
    8: 3,   # awning-tricycle -> motorcycle
    9: 5,   # bus -> bus
    10: 3,  # motor -> motorcycle
}


@dataclass
class MOTMetrics:
    """Standard Multi-Object Tracking evaluation metrics."""

    mota: float
    idf1: float
    id_switches: int
    fp: int
    fn: int
    tp: int
    total_gt: int
    precision: float
    recall: float
    fragmentations: int = 0


@dataclass
class AblationVariantResult:
    """Benchmark result for a single tracker configuration.

    Synthetic runs carry ``data_kind="synthetic"`` and must never be reported as
    real dataset benchmark measurements.
    """

    name: str
    use_class_aware: bool
    use_nsa: bool
    use_diou: bool
    use_vdc: bool
    use_oru: bool
    use_lazy_appearance: bool
    use_recovery_pool: bool
    metrics: MOTMetrics
    fps: float
    avg_track_ms: float
    data_kind: str = "synthetic"

    def to_dict(self) -> Dict[str, object]:
        return asdict(self)


def evaluate_mot(
    gt_by_frame: Dict[int, List[Tuple[int, np.ndarray]]],
    pred_by_frame: Dict[int, List[Tuple[int, np.ndarray]]],
    iou_thresh: float = 0.5,
) -> MOTMetrics:
    """Compute MOTA, IDF1, ID-Switches, Fragmentations, FP, FN, Precision, Recall."""
    all_frames = sorted(set(gt_by_frame.keys()) | set(pred_by_frame.keys()))

    total_gt = 0
    tp = 0
    fp = 0
    fn = 0
    id_switches = 0
    fragmentations = 0
    last_gt_match: Dict[int, int] = {}
    matched_before: set[int] = set()
    unmatched_since_match: set[int] = set()

    # For IDF1: count co-occurrences (gt_id, pred_id) -> matched_frames
    gt_counts: Dict[int, int] = {}
    pred_counts: Dict[int, int] = {}
    match_counts: Dict[Tuple[int, int], int] = {}

    for frame_id in all_frames:
        gts = gt_by_frame.get(frame_id, [])
        preds = pred_by_frame.get(frame_id, [])
        total_gt += len(gts)

        for gid, _ in gts:
            gt_counts[gid] = gt_counts.get(gid, 0) + 1
        for pid, _ in preds:
            pred_counts[pid] = pred_counts.get(pid, 0) + 1

        if not gts and not preds:
            continue
        if not gts:
            fp += len(preds)
            continue

        matched_gt_ids: set[int] = set()
        if not preds:
            fn += len(gts)
        else:
            gt_boxes = np.asarray([b for _, b in gts], dtype=np.float64)
            pred_boxes = np.asarray([b for _, b in preds], dtype=np.float64)
            ious = bbox_iou_matrix(gt_boxes, pred_boxes)
            cost = np.where(ious >= iou_thresh, 1.0 - ious, 1e6)
            row_ind, col_ind = linear_sum_assignment(cost)

            matched_gt = set()
            matched_pred = set()
            for r, c in zip(row_ind, col_ind):
                if ious[r, c] >= iou_thresh:
                    matched_gt.add(int(r))
                    matched_pred.add(int(c))
                    gid = gts[r][0]
                    pid = preds[c][0]
                    matched_gt_ids.add(gid)
                    tp += 1
                    match_counts[(gid, pid)] = match_counts.get((gid, pid), 0) + 1

                    if gid in last_gt_match and last_gt_match[gid] != pid:
                        id_switches += 1
                    last_gt_match[gid] = pid

            fn += len(gts) - len(matched_gt)
            fp += len(preds) - len(matched_pred)

        # Fragmentation: count transitions matched -> unmatched -> matched per GT track
        for gid, _ in gts:
            if gid in matched_gt_ids:
                if gid in matched_before and gid in unmatched_since_match:
                    fragmentations += 1
                unmatched_since_match.discard(gid)
                matched_before.add(gid)
            elif gid in matched_before:
                unmatched_since_match.add(gid)

    # Global bipartite matching for IDF1
    gt_ids = sorted(gt_counts.keys())
    pred_ids = sorted(pred_counts.keys())
    idtp = 0
    if gt_ids and pred_ids:
        score_mat = np.zeros((len(gt_ids), len(pred_ids)), dtype=np.float64)
        for i, gid in enumerate(gt_ids):
            for j, pid in enumerate(pred_ids):
                score_mat[i, j] = match_counts.get((gid, pid), 0)
        r_ind, c_ind = linear_sum_assignment(-score_mat)
        idtp = int(sum(score_mat[r, c] for r, c in zip(r_ind, c_ind)))

    total_pred = sum(pred_counts.values())
    idf1 = (2.0 * idtp) / max(total_gt + total_pred, 1)
    mota = 1.0 - (fn + fp + id_switches) / max(total_gt, 1)
    precision = tp / max(tp + fp, 1)
    recall = tp / max(tp + fn, 1)

    return MOTMetrics(
        mota=round(float(mota), 4),
        idf1=round(float(idf1), 4),
        id_switches=int(id_switches),
        fp=int(fp),
        fn=int(fn),
        tp=int(tp),
        total_gt=int(total_gt),
        precision=round(float(precision), 4),
        recall=round(float(recall), 4),
        fragmentations=int(fragmentations),
    )


def generate_occlusion_benchmark(
    num_frames: int = 150,
    num_targets: int = 8,
    seed: int = 42,
) -> Tuple[Dict[int, List[Tuple[int, np.ndarray]]], Dict[int, List[Detection]]]:
    """Generate a synthetic multi-class crossing, curved-occlusion & noisy-confidence benchmark.

    WARNING: Synthetic diagnostic benchmark only (``data_kind="synthetic"``).
    Simulates crossing ``person`` / ``car`` / ``motorcycle`` trajectories with gentle
    curved motion and partial/full occlusion windows so all ByteTrack enhancements
    (ClassAware, NSA-Kalman, DIoU+VDC/ORU, LazyAppearance) can be verified cleanly.
    """
    rng = np.random.default_rng(seed)
    gt_by_frame: Dict[int, List[Tuple[int, np.ndarray]]] = {}
    dets_by_frame: Dict[int, List[Detection]] = {}

    class_specs = [
        (0, "person", 32.0, 72.0),
        (2, "car", 64.0, 48.0),
        (3, "motorcycle", 42.0, 56.0),
    ]

    mid_frame = max(20, num_frames // 2)
    targets = []
    for tid in range(1, num_targets + 1):
        pair_idx = (tid - 1) // 2
        direction = 1.0 if tid % 2 == 1 else -1.0
        if pair_idx == 0:
            cls_id, cls_name, w, h = class_specs[0 if tid % 2 == 1 else 1]
        elif pair_idx == 1:
            cls_id, cls_name, w, h = class_specs[2 if tid % 2 == 1 else 1]
        elif pair_idx == 2:
            cls_id, cls_name, w, h = class_specs[0]
        else:
            cls_id, cls_name, w, h = class_specs[tid % 3]

        base_y = 75.0 + pair_idx * 95.0
        # Pair 0 (person vs car) and Pair 2 (person vs person) cross directly on the same line
        y_offset = 0.0 if pair_idx in (0, 2) else (-6.0 if direction > 0 else 6.0)
        y0 = base_y + y_offset
        speed = 4.2 if pair_idx in (0, 2) else float(rng.uniform(3.4, 4.0))
        vx = direction * speed
        x0 = 320.0 - vx * (mid_frame - 1)
        vy = 0.0 if pair_idx in (0, 2) else float(rng.uniform(-0.10, 0.10))

        occ_start = max(14, mid_frame + 12 - (pair_idx % 2) * 3)
        occ_len = 6 if pair_idx != 2 else 4
        curve_shift = (1.0 if tid % 2 == 1 else -1.0) * (14.0 if pair_idx == 1 else 0.0)
        targets.append(
            (tid, pair_idx, cls_id, cls_name, x0, y0, vx, vy, w, h, occ_start, occ_len, curve_shift)
        )

    for f in range(1, num_frames + 1):
        gts: List[Tuple[int, np.ndarray]] = []
        dets: List[Detection] = []
        for (
            tid,
            pair_idx,
            cls_id,
            cls_name,
            x0,
            y0,
            vx,
            vy,
            w,
            h,
            occ_start,
            occ_len,
            curve_shift,
        ) in targets:
            cx = x0 + vx * (f - 1)
            cy = y0 + vy * (f - 1)
            if curve_shift != 0.0 and f >= occ_start:
                progress = min(1.0, (f - occ_start + 1) / float(max(1, occ_len)))
                cy += curve_shift * 0.5 * (1.0 - float(np.cos(np.pi * progress)))

            gt_box = np.array(
                [cx - 0.5 * w, cy - 0.5 * h, cx + 0.5 * w, cy + 0.5 * h],
                dtype=np.float32,
            )
            gts.append((tid, gt_box))

            # Pair 1: pre-occlusion low-conf noisy spike to exercise NSA-Kalman
            if pair_idx == 1 and f in (occ_start - 2, occ_start - 1) and tid % 2 == 1:
                noisy_shift = np.array([-22.0, 14.0, -22.0, 14.0], dtype=np.float32) * (
                    1.0 if vx > 0 else -1.0
                )
                dets.append(Detection(gt_box + noisy_shift, 0.13, cls_id, cls_name))
                continue

            if occ_start <= f < occ_start + occ_len:
                if f < occ_start + occ_len // 2:
                    continue
                jitter = rng.normal(0.0, 2.0, size=4).astype(np.float32)
                conf = float(rng.uniform(0.24, 0.38))
                dets.append(Detection(gt_box + jitter, conf, cls_id, cls_name))
            else:
                jitter = rng.normal(0.0, 0.8, size=4).astype(np.float32)
                conf = float(rng.uniform(0.80, 0.96))
                dets.append(Detection(gt_box + jitter, conf, cls_id, cls_name))

        gt_by_frame[f] = gts
        dets_by_frame[f] = dets

    return gt_by_frame, dets_by_frame


def generate_synthetic_frames(
    gt_by_frame: Dict[int, List[Tuple[int, np.ndarray]]],
    frame_size: Tuple[int, int] = (480, 640),
) -> Dict[int, np.ndarray]:
    """Render tiny colored BGR frames matching GT boxes so LazyAppearance can extract HSV features."""
    import cv2

    max_x = frame_size[1]
    max_y = frame_size[0]
    for boxes in gt_by_frame.values():
        for _, box in boxes:
            max_x = max(max_x, int(np.ceil(box[2])) + 16)
            max_y = max(max_y, int(np.ceil(box[3])) + 16)
    height, width = max_y, max_x

    color_cache: Dict[int, Tuple[Tuple[int, int, int], Tuple[int, int, int]]] = {}

    def _get_colors(tid: int) -> Tuple[Tuple[int, int, int], Tuple[int, int, int]]:
        if tid not in color_cache:
            hue_top = int((tid * 47) % 180)
            hue_bot = int((tid * 47 + 65) % 180)
            hsv_pair = np.array([[[hue_top, 220, 220]], [[hue_bot, 200, 190]]], dtype=np.uint8)
            bgr_pair = cv2.cvtColor(hsv_pair, cv2.COLOR_HSV2BGR)
            top = tuple(int(c) for c in bgr_pair[0, 0])
            bot = tuple(int(c) for c in bgr_pair[1, 0])
            color_cache[tid] = (top, bot)
        return color_cache[tid]

    frames: Dict[int, np.ndarray] = {}
    for frame_id, boxes in gt_by_frame.items():
        canvas = np.full((height, width, 3), 36, dtype=np.uint8)
        for tid, box in boxes:
            x1 = max(0, int(round(float(box[0]))))
            y1 = max(0, int(round(float(box[1]))))
            x2 = min(width, int(round(float(box[2]))))
            y2 = min(height, int(round(float(box[3]))))
            if x2 <= x1 + 2 or y2 <= y1 + 2:
                continue
            mid_y = (y1 + y2) // 2
            top_bgr, bot_bgr = _get_colors(tid)
            cv2.rectangle(canvas, (x1, y1), (x2, mid_y), top_bgr, thickness=-1)
            cv2.rectangle(canvas, (x1, mid_y), (x2, y2), bot_bgr, thickness=-1)

        # Preserve visible side slice when two boxes overlap on the same lane
        for i in range(len(boxes)):
            tid_a, ba = boxes[i]
            ax1, ay1, ax2, ay2 = [max(0, int(round(float(v)))) for v in ba]
            amid_y = (ay1 + ay2) // 2
            for j in range(i + 1, len(boxes)):
                tid_b, bb = boxes[j]
                bx1, by1, bx2, by2 = [max(0, int(round(float(v)))) for v in bb]
                if ax1 < bx2 and bx1 < ax2 and ay1 < by2 and by1 < ay2:
                    # Paint leftmost half for left-most box and rightmost half for right-most box
                    split_x = max(min((ax1 + ax2 + bx1 + bx2) // 4, width), 0)
                    top_a, bot_a = _get_colors(tid_a)
                    if ax1 < bx1 and split_x > ax1:
                        cv2.rectangle(canvas, (ax1, ay1), (min(ax2, split_x), amid_y), top_a, thickness=-1)
                        cv2.rectangle(canvas, (ax1, amid_y), (min(ax2, split_x), ay2), bot_a, thickness=-1)
        frames[frame_id] = canvas
    return frames


def load_mot_gt(
    gt_path: str | Path,
    ignore_zero_flag: bool = False,
) -> Dict[int, List[Tuple[int, np.ndarray]]]:
    """Load MOTChallenge-format ground truth file (frame,id,x,y,w,h,...)."""
    path = Path(gt_path)
    if not path.is_file():
        raise FileNotFoundError(f"MOT ground-truth file not found: {path}")

    gt_by_frame: Dict[int, List[Tuple[int, np.ndarray]]] = {}
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            stripped = line.strip()
            if not stripped:
                continue
            parts = stripped.split(",")
            if len(parts) < 6:
                continue
            if ignore_zero_flag and len(parts) >= 7 and float(parts[6]) == 0.0:
                continue
            frame_id = int(float(parts[0]))
            track_id = int(float(parts[1]))
            x, y, w, h = map(float, parts[2:6])
            if w <= 0.0 or h <= 0.0:
                continue
            box = np.array([x, y, x + w, y + h], dtype=np.float32)
            gt_by_frame.setdefault(frame_id, []).append((track_id, box))
    return gt_by_frame


def load_visdrone_mot_gt(
    gt_path: str | Path,
) -> Tuple[Dict[int, List[Tuple[int, np.ndarray]]], Dict[int, Dict[int, int]]]:
    """Load VisDrone2019-MOT 10-column ground truth file mapped to COCO classes.

    Line format: ``frame,id,x,y,w,h,score,category,truncation,occlusion``.
    Ignores category ``0`` (ignored regions) and ``11`` (others).

    Returns:
        Tuple ``(gt_by_frame, classes_by_frame)`` where ``classes_by_frame[frame_id][track_id]``
        holds the mapped COCO class ID.
    """
    path = Path(gt_path)
    if not path.is_file():
        raise FileNotFoundError(f"VisDrone ground-truth file not found: {path}")

    gt_by_frame: Dict[int, List[Tuple[int, np.ndarray]]] = {}
    classes_by_frame: Dict[int, Dict[int, int]] = {}
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            stripped = line.strip()
            if not stripped:
                continue
            parts = stripped.split(",")
            if len(parts) < 8:
                continue
            category = int(float(parts[7]))
            if category in (0, 11) or category not in VISDRONE_TO_COCO_MAP:
                continue
            frame_id = int(float(parts[0]))
            track_id = int(float(parts[1]))
            x, y, w, h = map(float, parts[2:6])
            if w <= 0.0 or h <= 0.0:
                continue
            box = np.array([x, y, x + w, y + h], dtype=np.float32)
            gt_by_frame.setdefault(frame_id, []).append((track_id, box))
            classes_by_frame.setdefault(frame_id, {})[track_id] = VISDRONE_TO_COCO_MAP[category]
    return gt_by_frame, classes_by_frame


def build_ablation_variants() -> List[Tuple[str, ByteTrackerConfig]]:
    """Return the canonical 6 ByteTrack ablation variants starting from true official baseline."""
    return [
        ("Baseline (Standard ByteTrack)", ByteTrackerConfig.official_baseline()),
        (
            "+ClassAware",
            ByteTrackerConfig(
                use_recovery_pool=True,
                use_class_aware=True,
                use_nsa=False,
                use_diou=False,
                use_vdc=False,
                use_oru=False,
                use_lazy_appearance=False,
            ),
        ),
        (
            "+NSA-Kalman",
            ByteTrackerConfig(
                use_recovery_pool=True,
                use_class_aware=True,
                use_nsa=True,
                use_diou=False,
                use_vdc=False,
                use_oru=False,
                use_lazy_appearance=False,
            ),
        ),
        (
            "+DIoU+VDC/ORU",
            ByteTrackerConfig(
                use_recovery_pool=True,
                use_class_aware=True,
                use_nsa=True,
                use_diou=True,
                use_vdc=True,
                use_oru=True,
                use_lazy_appearance=False,
            ),
        ),
        (
            "+LazyAppearance",
            ByteTrackerConfig(
                use_recovery_pool=True,
                use_class_aware=True,
                use_nsa=True,
                use_diou=True,
                use_vdc=True,
                use_oru=True,
                use_lazy_appearance=True,
            ),
        ),
        ("Full (Enhanced ByteTrack)", ByteTrackerConfig.full_enhanced()),
    ]


def run_ablation_suite(
    gt_by_frame: Optional[Dict[int, List[Tuple[int, np.ndarray]]]] = None,
    dets_by_frame: Optional[Dict[int, List[Detection]]] = None,
    frames_by_frame: Optional[Dict[int, np.ndarray]] = None,
    num_frames: int = 150,
    num_targets: int = 8,
    seed: int = 42,
    data_kind: str = "synthetic",
) -> List[AblationVariantResult]:
    """Run all 6 ByteTrack ablation variants (from true official baseline) and return results."""
    is_synthetic = gt_by_frame is None or dets_by_frame is None
    if is_synthetic:
        gt_by_frame, dets_by_frame = generate_occlusion_benchmark(
            num_frames=num_frames, num_targets=num_targets, seed=seed
        )
        if frames_by_frame is None:
            frames_by_frame = generate_synthetic_frames(gt_by_frame)
        effective_data_kind = "synthetic"
    else:
        effective_data_kind = data_kind

    variants = build_ablation_variants()
    frames = sorted(set(gt_by_frame.keys()) | set(dets_by_frame.keys()))
    results: List[AblationVariantResult] = []

    for name, cfg in variants:
        tracker = ByteTracker(cfg)
        pred_by_frame: Dict[int, List[Tuple[int, np.ndarray]]] = {}

        t0 = time.perf_counter()
        for f in frames:
            frame_img = frames_by_frame.get(f) if frames_by_frame is not None else None
            tracks = tracker.update(
                dets_by_frame.get(f, []), frame_id=f, frame=frame_img
            )
            pred_by_frame[f] = [
                (t.track_id, t.xyxy.astype(np.float32)) for t in tracks
            ]
        elapsed = max(time.perf_counter() - t0, 1e-9)

        metrics = evaluate_mot(gt_by_frame, pred_by_frame)
        fps = len(frames) / elapsed
        avg_ms = (elapsed * 1000.0) / max(len(frames), 1)
        results.append(
            AblationVariantResult(
                name=name,
                use_class_aware=cfg.use_class_aware,
                use_nsa=cfg.use_nsa,
                use_diou=cfg.use_diou,
                use_vdc=cfg.use_vdc,
                use_oru=cfg.use_oru,
                use_lazy_appearance=cfg.use_lazy_appearance,
                use_recovery_pool=cfg.use_recovery_pool,
                metrics=metrics,
                fps=round(float(fps), 2),
                avg_track_ms=round(float(avg_ms), 4),
                data_kind=effective_data_kind,
            )
        )

    return results


def run_video_ablation(
    video_path: str | Path,
    gt_path: str | Path,
    detector: DetectorAdapter,
    data_kind: str = "public_benchmark",
) -> List[AblationVariantResult]:
    """Run ablation suite on a real video file with MOT-format ground truth."""
    import cv2

    v_path = Path(video_path)
    g_path = Path(gt_path)
    if not v_path.is_file():
        raise FileNotFoundError(f"Video file not found: {v_path}")
    if not g_path.is_file():
        raise FileNotFoundError(f"Ground-truth file not found: {g_path}")

    gt_by_frame = load_mot_gt(g_path, ignore_zero_flag=True)
    dets_by_frame: Dict[int, List[Detection]] = {}
    frames_by_frame: Dict[int, np.ndarray] = {}
    cap = cv2.VideoCapture(str(v_path))
    frame_id = 0
    try:
        while cap.isOpened():
            ok, frame = cap.read()
            if not ok or frame is None:
                break
            frame_id += 1
            dets_by_frame[frame_id] = detector.detect(frame)
            if frame_id <= 600:
                frames_by_frame[frame_id] = frame
    finally:
        cap.release()
    return run_ablation_suite(
        gt_by_frame=gt_by_frame,
        dets_by_frame=dets_by_frame,
        frames_by_frame=frames_by_frame if len(dets_by_frame) <= 600 else None,
        data_kind=data_kind,
    )
